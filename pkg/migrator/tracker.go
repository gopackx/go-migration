package migrator

import (
	"database/sql"
	"fmt"
	"time"

	"github.com/gopackx/go-migration/pkg/schema"
	"github.com/gopackx/go-migration/pkg/schema/grammars"
)

// MigrationRecord represents a single row in the migration tracking table.
type MigrationRecord struct {
	Name      string
	Batch     int
	CreatedAt time.Time
}

// Tracker manages the migrations tracking table in the database.
//
// The SQL dialect (DDL for the tracking table and bind-parameter placeholders)
// comes from a schema.Grammar. NewTracker uses a PostgreSQL-compatible
// default; use NewTrackerWithGrammar for MySQL or SQLite.
type Tracker struct {
	db        *sql.DB
	tableName string
	grammar   schema.Grammar
}

// NewTracker creates a new Tracker that uses the given database connection
// and stores records in the specified table. It uses PostgreSQL syntax
// (SERIAL, $N placeholders); use NewTrackerWithGrammar for other databases.
func NewTracker(db *sql.DB, tableName string) *Tracker {
	return NewTrackerWithGrammar(db, tableName, nil)
}

// NewTrackerWithGrammar creates a new Tracker whose SQL is generated by the
// given grammar. A nil grammar falls back to the PostgreSQL grammar.
func NewTrackerWithGrammar(db *sql.DB, tableName string, g schema.Grammar) *Tracker {
	if g == nil {
		g = grammars.NewPostgresGrammar()
	}
	return &Tracker{
		db:        db,
		tableName: tableName,
		grammar:   g,
	}
}

// EnsureTable creates the migration tracking table if it does not already exist.
// This operation is idempotent — calling it multiple times has no effect.
func (t *Tracker) EnsureTable() error {
	query := t.grammar.CompileTrackingTable(t.tableName)

	if _, err := t.db.Exec(query); err != nil {
		return fmt.Errorf("ensure tracking table %q: %w: %w", t.tableName, ErrTrackingTable, err)
	}
	return nil
}

// TableExists reports whether the tracking table exists, using the grammar's
// CompileHasTable query. It is read-only and is used instead of EnsureTable
// in dry-run mode.
func (t *Tracker) TableExists() (bool, error) {
	query := t.grammar.CompileHasTable(t.tableName)

	var count int
	if err := t.db.QueryRow(query).Scan(&count); err != nil {
		return false, fmt.Errorf("check tracking table %q: %w: %w", t.tableName, ErrTrackingTable, err)
	}
	return count > 0, nil
}

// GetApplied returns all migration records ordered by name ascending.
func (t *Tracker) GetApplied() ([]MigrationRecord, error) {
	query := fmt.Sprintf(
		`SELECT migration, batch, created_at FROM %s ORDER BY migration ASC`,
		t.tableName,
	)

	rows, err := t.db.Query(query)
	if err != nil {
		return nil, fmt.Errorf("get applied migrations: %w: %w", ErrTrackingTable, err)
	}
	defer rows.Close()

	return scanRecords(rows)
}

// GetByBatch returns all migration records for the given batch number,
// ordered by name ascending.
func (t *Tracker) GetByBatch(batch int) ([]MigrationRecord, error) {
	query := fmt.Sprintf(
		`SELECT migration, batch, created_at FROM %s WHERE batch = %s ORDER BY migration ASC`,
		t.tableName, t.grammar.Placeholder(1),
	)

	rows, err := t.db.Query(query, batch)
	if err != nil {
		return nil, fmt.Errorf("get migrations for batch %d: %w: %w", batch, ErrTrackingTable, err)
	}
	defer rows.Close()

	return scanRecords(rows)
}

// scanRecords reads all migration records from rows.
func scanRecords(rows *sql.Rows) ([]MigrationRecord, error) {
	var records []MigrationRecord
	for rows.Next() {
		var r MigrationRecord
		var created flexTime
		if err := rows.Scan(&r.Name, &r.Batch, &created); err != nil {
			return nil, fmt.Errorf("scan migration record: %w: %w", ErrTrackingTable, err)
		}
		r.CreatedAt = created.Time
		records = append(records, r)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterate migration records: %w: %w", ErrTrackingTable, err)
	}
	return records, nil
}

// GetLastBatchNumber returns the highest batch number in the tracking table.
// Returns 0 if no records exist.
func (t *Tracker) GetLastBatchNumber() (int, error) {
	query := fmt.Sprintf(
		`SELECT COALESCE(MAX(batch), 0) FROM %s`,
		t.tableName,
	)

	var batch int
	if err := t.db.QueryRow(query).Scan(&batch); err != nil {
		return 0, fmt.Errorf("get last batch number: %w: %w", ErrTrackingTable, err)
	}
	return batch, nil
}

// Record inserts a new migration record with the given name and batch number.
func (t *Tracker) Record(name string, batch int) error {
	return t.RecordTx(t.db, name, batch)
}

// RecordTx inserts a new migration record using the given executor, which is
// typically the *sql.Tx the migration itself ran in, so that the migration and
// its tracking row are committed (or rolled back) together.
func (t *Tracker) RecordTx(ex schema.Executor, name string, batch int) error {
	query := fmt.Sprintf(
		`INSERT INTO %s (migration, batch) VALUES (%s, %s)`,
		t.tableName, t.grammar.Placeholder(1), t.grammar.Placeholder(2),
	)

	if _, err := ex.Exec(query, name, batch); err != nil {
		return fmt.Errorf("record migration %q: %w: %w", name, ErrTrackingTable, err)
	}
	return nil
}

// Remove deletes a migration record by name.
func (t *Tracker) Remove(name string) error {
	return t.RemoveTx(t.db, name)
}

// RemoveTx deletes a migration record by name using the given executor,
// typically the *sql.Tx the migration's Down ran in.
func (t *Tracker) RemoveTx(ex schema.Executor, name string) error {
	query := fmt.Sprintf(
		`DELETE FROM %s WHERE migration = %s`,
		t.tableName, t.grammar.Placeholder(1),
	)

	if _, err := ex.Exec(query, name); err != nil {
		return fmt.Errorf("remove migration %q: %w: %w", name, ErrTrackingTable, err)
	}
	return nil
}

// flexTime scans a timestamp column regardless of how the driver returns it.
// lib/pq and pgx return time.Time; go-sql-driver/mysql returns []byte unless
// the DSN sets parseTime=true; SQLite drivers may return a string.
type flexTime struct {
	Time time.Time
}

// timeLayouts are the textual timestamp formats accepted by flexTime.
var timeLayouts = []string{
	"2006-01-02 15:04:05.999999999-07:00",
	"2006-01-02T15:04:05.999999999-07:00",
	"2006-01-02 15:04:05.999999999",
	"2006-01-02T15:04:05.999999999",
	"2006-01-02 15:04:05",
	"2006-01-02T15:04:05",
	time.RFC3339Nano,
	"2006-01-02",
}

// Scan implements sql.Scanner.
func (f *flexTime) Scan(src any) error {
	switch v := src.(type) {
	case nil:
		f.Time = time.Time{}
		return nil
	case time.Time:
		f.Time = v
		return nil
	case []byte:
		return f.parse(string(v))
	case string:
		return f.parse(v)
	default:
		return fmt.Errorf("unsupported created_at type %T", src)
	}
}

func (f *flexTime) parse(s string) error {
	for _, layout := range timeLayouts {
		if t, err := time.Parse(layout, s); err == nil {
			f.Time = t
			return nil
		}
	}
	return fmt.Errorf("cannot parse created_at value %q", s)
}
